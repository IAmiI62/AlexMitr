#Сумма половин
#Дано натуральное число, состоящее из четного количества цифр. Десятичная запись числа разрезается посередине. Найдите сумму первой и второй половины числа. Например для 206198 ответом будет 404, так как 206+198=404.

#Формат входных данных
#Одно целое положительное число, состоящее из четного количества цифр

#Формат результата
#Одно число — ответ к задаче.

n = input().strip()

m = len(n)//2

f = int(n[:m])
s = int(n[m:])

print(s+f)
