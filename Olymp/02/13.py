#Для заданного числа n найти сумму его делителей, которые меньше n.

#Формат входных данных
#Одно натуральное число n, 2≤n≤1000000

#Формат результата
#Одно число — ответ к задаче.

n = int(input())
sum = 1

for i in range(2, int(n ** 0.5) + 1):
    if n % i == 0:
        sum += i
        if i != n // i:
            sum += n // i

print(sum)
