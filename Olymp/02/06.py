#Деду Морозу требуется положить в каждый из n подарков по m конфет. Конфеты лежат в коробках, в каждой коробке ровно k конфет. Какое количество коробок придется раскрыть, чтобы собрать все подарки?

#Формат входных данных
#Через пробел записаны три натуральных числа n, m, k. Все числа не превышают 1000.

#Формат результата
#Вывести одно число — ответ к задаче.
  
n, m,k = map(int, input().split())
totl = n * m

box = (totl + k - 1)//k
print(box)
