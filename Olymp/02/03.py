#У трех путешественников в пустыне осталось n литров воды. Они решили поделить воду поровну. Сколько воды получит каждый. Выведите ответ с точностью до миллилитра

#Формат входных данных
#Одно натуральное число n.

#Формат результата
#Одно вещественное число c заданной точностью

n = float(input())
