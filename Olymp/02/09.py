#Задана строка, состоящая из цифр и символов латинского алфавита. Напишите программу, которая найдет сумму всех цифр. Строка может не содержать цифр. В этом случае ответом должен быть ноль.

#Формат входных данных
#Одна строка, состоящая из цифр и символов латинского алфавита .

#Формат результата
#Одно число — сумма всех цифр.
    
s = input()

sum = 0
for char in s:
    if char.isdigit():
        sum += int(char)

print(sum)
