#В одной строке через пробел записано несколько слов. Программа должна развернуть каждое из слов и вывести их в том же порядке.

#Формат входных данных
#Одна строка, состоящая из пробелов и символов латиницы.

#Формат результата
#Одна строка — результат разворота каждого из слов.

words = input().split()
res = []  

for word in words:
    revers = word[::-1] 
    res.append(revers)  


print(" ".join(res))
