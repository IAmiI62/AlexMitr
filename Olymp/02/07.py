#Датчик пульса засек n ударов сердца за t секунд. Требуется найти количество ударов сердца в минуту. Ответ требуется округлить вверх до ближайшего целого числа.

#Формат входных данных
#Через пробел записаны два числа: натуральное n > 2 и вещественное t.

#Формат результата
#Вывести одно целое число — ответ к задаче.

n, t = input().split()
n = int(n)
t = float(t)

bpm = n * 60 / t

res = int(-(-bpm // 1))

print(res)
